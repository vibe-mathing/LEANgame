let lang = document.documentElement.lang === 'en' ? 'en' : 'he';

export const getLang = () => lang;

export function setLang(l) {
  lang = l === 'en' ? 'en' : 'he';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'he' ? 'rtl' : 'ltr';
  try { localStorage.setItem('lg.lang', JSON.stringify(lang)); } catch { /* private mode */ }
}

export function t(key, vars) {
  let s = STR[lang][key] ?? STR.he[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  return s;
}

// Pick the current language from a { he, en } object.
export const L = (o) => (o == null ? '' : typeof o === 'string' ? o : o[lang] ?? o.he);

export const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

// Typeset a math string: points in italics, always left to right.
export function mathHTML(s) {
  return esc(s).replace(/[A-Z]/g, '<var>$&</var>');
}
export const mathSpan = (s) => `<span class="math" dir="ltr">${mathHTML(s)}</span>`;

// Trusted text with $math$ segments.
export const rich = (s) => String(s).replace(/\$([^$]+)\$/g, (_, m) => mathSpan(m));
