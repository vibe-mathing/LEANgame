// Playable problems for geometry stages 4–11 (L04–L11), in the format of PROBLEMS in
// data.js. Coordinates are math coordinates (y up), a witness that the givens fit
// together; points that lie on one line are placed exactly on it, because rays and lines
// are read off the coordinates. Angles in the givens match the drawing to within a degree.
// Every figure is built by a function, since prepareProblem() writes into the object.

const on = (o, a, b) => ({
  type: 'between', a, o, b, lean: `Sbtw ℝ ${a} ${o} ${b}`,
  text: { he: `$${o}$ נמצאת על $${a}${b}$`, en: `$${o}$ lies on $${a}${b}$` },
});
const circle = (o, pts) => ({
  type: 'circle', o, on: pts, lean: pts.map((p) => `len ${o} ${p} = r`).join(' ∧ '),
  text: { he: `$${pts.join('$, $')}$ על המעגל שמרכזו $${o}$`, en: `$${pts.join('$, $')}$ lie on the circle with center $${o}$` },
});
const tangent = (p, t, o) => ({
  type: 'tangent', p, t, o, lean: `IsTangent ${p} ${t} ${o} r`,
  text: { he: `$${p}${t}$ משיק למעגל בנקודה $${t}$`, en: `$${p}${t}$ is tangent to the circle at $${t}$` },
});
const mid = (m, a, b) => ({
  claim: `${a}${m} = ${m}${b}`, also: ['midpoint_def'],
  text: { he: `$${m}$ אמצע $${a}${b}$`, en: `$${m}$ is the midpoint of $${a}${b}$` },
});
const H = (he, en) => ({ he, en });

